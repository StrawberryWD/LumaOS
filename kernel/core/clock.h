/* kernel/core/clock.h - DAY72+: 毫秒时间基（TSC，用 PIT 通道 2 校准）
 *
 * 为什么需要：GUI 主循环没有定时器中断（IRQ0 没有被使用），以前“光标闪烁”和“每 15 帧重绘”都是按“循环/重绘次数”
 * 计数的。QEMU(TCG) 里循环只有 ~160 次/秒，看起来正常；换到 VMware（CPU 快得多、循环可达每秒上万次）
 * 闪烁就快了几十倍，而且桌面每秒被整屏重绘/提交给虚拟显卡成千上万次，鼠标快速滑动时
 * 显卡 FIFO 被塞满，驱动就在 SVGA_SYNC 上忙等 -> 卡顿。有了真实的毫秒，两个问题都按“时间”而不是“次数”处理。
 *
 * 做法：第一次使用时让 PIT 通道 2（独立于 IRQ，只是一个 1193182 Hz 的递减计数器，端口 0x61 控制门）数 20ms，
 * 同时读 TSC 前后差，得到“每毫秒多少个 TSC 周期”。之后 clock_ms() = TSC 经过的周期数 / 每毫秒周期数。
 * i386 没有 libgcc，不能做 64 位除法：这里每次调用只取“距上次调用”的增量，增量 < 2^32 周期时用普通 32 位除法，
 * 余数保留（不丢精度）；超过 100ms 的长间隔按 100ms 一块累加。
 */
#ifndef LUMA_CLOCK_H
#define LUMA_CLOCK_H
#include <stdint.h>
uint32_t clock_ms(void);          /* 自第一次调用起的毫秒数（约 49 天回绕）*/
uint32_t clock_tsc_khz(void);     /* 校准得到的 TSC 频率（kHz），调试用 */
#endif

/* kernel/mm/aspace.h - LumaOS 5.0
 *
 * DAY54 (Week 8, Day 54): "独立用户地址空间。"  验收："ELF 在独立虚拟地址空间运行。"
 *
 * ===================================================================================
 *  什么是“地址空间”
 * ===================================================================================
 *  Day 53 的内核页表是恒等映射：线性地址 == 物理地址。程序的 p_vaddr 0x08048000 就是物理内存
 *  的第 128MB 处——程序和内核看到的是同一份内存，程序想改哪里就改哪里。
 *
 *  地址空间 = 一个页目录（CR3 指向它）+ 它引用的全部页表。切换 CR3，CPU 看到的“线性地址 ->
 *  物理地址”整张表就换了一套。于是：
 *      同一个线性地址 0x08048000 -> 在进程 A 的页目录里指向物理页框 X，
 *                                  在进程 B 的页目录里指向物理页框 Y（或者根本不存在）。
 *  程序的“地址 0x08048000”只是一个名字，背后的物理页框由内核分配、内核决定。
 *
 * ===================================================================================
 *  LumaOS 的进程地址空间布局（今天，程序仍在 Ring 0）
 * ===================================================================================
 *   页目录项（每项管 4MB）          内容                                       谁的
 *   PDE[0..3]    线性 0~16MB        内核：.text/.data/.bss、栈、GUI 缓冲、       共享（和内核页目录
 *                                   页框池 [8MB,16MB)、VGA 窗口                  指向同一批页表）
 *   PDE[4..59]   线性 16MB~240MB    ★ 用户区：ELF 的段、用户栈                  每个进程自己的
 *                                   （没映射的页 = 不存在，访问即 #PF）
 *   PDE[60..63]  线性 240~256MB     内核页表里的恒等映射                        共享
 *   PDE[64..1023] 线性 256MB~4GB    4MB 大页：PCI MMIO / 显存（不缓存）          共享
 *  共享的意思是：进程页目录的这些 PDE 直接拷贝内核页目录里的值，指向同一批页表。所以内核代码
 *  在任何进程的 CR3 下都能运行（中断来了、系统调用进来了，内核都不用先切回内核页目录）——
 *  这是一切 OS 的标准做法：每个进程的地址空间里都带着一份内核。
 *  用户区 [16MB,240MB) 正是 ELF_LOAD_MIN_ADDR ~ ELF_LOAD_MAX_ADDR（elf.h），刚好是 PDE 4..59，
 *  边界落在 4MB 的整数倍上——这不是巧合，是选常量时就为这一天留好的。
 *
 *  用户区里的页怎么来：
 *      ELF 的 PT_LOAD 段   [p_vaddr, p_vaddr+p_memsz) 按页向外取整  -> 每页一个新页框（已清零）
 *      用户栈              [0x09FF0000, 0x0A000000) 共 16 页          -> 每页一个新页框
 *      栈底下面那一页 [0x09FEF000, 0x09FF0000) 故意不映射 = 硬件“护栏页”：栈溢出越过 64KB
 *      栈底，下一次 push 立刻 #PF，而不是悄悄改写别人的内存（Day 56 会把它变成“杀死进程”）。
 *  页框来自 pmm（物理 [8MB,16MB) 的页框池），物理地址和线性地址毫无关系：
 *      线性 0x08048000 -> 物理 0x0080xxxx。内核在内核页目录下仍然能用物理地址读写它们。
 *
 *  运行一个程序：
 *      aspace_create -> aspace_map_range（段、栈）-> aspace_activate（CR3 = 进程页目录）
 *      -> elf_load_segments / elf_run（它们照旧往 p_vaddr 写，现在被页表翻译到页框里）
 *      -> aspace_deactivate（CR3 = 内核页目录）-> aspace_destroy（页框全部还给 pmm）
 *  验证“真的独立”：程序跑完后，内核页目录下看到的物理地址 0x08048000 里仍然是 0——
 *  程序的代码在别处的页框里，从来没有写过那个物理地址。
 *
 * ===================================================================================
 *  今天的局限
 * ===================================================================================
 *   - [Day 55 已解决] 程序现在在 Ring 3 运行：用户区的页目录项和页表项都带 US 位，内核的页没有，
 *     程序碰内核内存就 #PF（保护违例）。运行时页（urt.h）被 aspace_protect_ro 改成只读。（下面 Day 54 当天的
 *     说明保留作参考：“程序仍在 Ring 0 / 页表项没有 US 位 / 照样能读写内核的页”是 Day 54 的状态。）
 *   - [Day 54 的状态] 程序仍在 Ring 0，页表项没有 US（用户可访问）位：硬件还不区分内核和用户。
 *   - 所有页都可写（包括代码页）。给只读段设只读要等 Day 55~56。
 *   - 缺页仍然 panic（Day 56 才改成“杀掉出错的程序、回到 shell”）。
 *   - 一次只有一个活动进程；没有按需分页（段和栈在运行前一次性映射好）、没有页框共享/写时复制。
 */
#ifndef LUMA_ASPACE_H
#define LUMA_ASPACE_H

#include <stdint.h>

#define ASPACE_USER_LO   0x01000000u   /* = ELF_LOAD_MIN_ADDR = LUMA_USER_LO */
#define ASPACE_USER_HI   0x0F000000u   /* = ELF_LOAD_MAX_ADDR = LUMA_USER_HI */
#define ASPACE_PDE_LO    (ASPACE_USER_LO >> 22)    /* 4  */
#define ASPACE_PDE_HI    (ASPACE_USER_HI >> 22)    /* 60 */

typedef struct {
    uint32_t pd_phys;      /* 页目录的物理地址（装进 CR3 的值）；0 = 未创建 */
    uint32_t frames;       /* 这个地址空间一共占用的页框数（页目录 + 页表 + 数据页）*/
    uint32_t data_pages;   /* 其中映射给用户区的数据页数 */
} aspace_t;

/* 创建：分配页目录，共享 PDE 照内核页目录拷贝，用户区全空。池空返回 -1。 */
int aspace_create(aspace_t *as);
/* 在用户区映射 [lo, hi) 里的每一页（按页取整；已映射的页跳过）。每页一个新页框（已清零），可写。
 * 区间必须落在 [ASPACE_USER_LO, ASPACE_USER_HI)，否则 -1；池空 -1（已映射的部分保留，由 destroy 回收）。 */
int aspace_map_range(aspace_t *as, uint32_t lo, uint32_t hi);
/* DAY55: 把已映射的用户页 va 改成只读（用户写它 -> #PF 保护违例；CR0.WP=1 所以内核写也一样）。 */
int aspace_protect_ro(aspace_t *as, uint32_t va);
/* 在该地址空间里翻译 va；成功 0，*pa 为物理地址；未映射 -1。不访问 va。 */
int aspace_translate(const aspace_t *as, uint32_t va, uint32_t *pa);
/* 切换 CR3。activate 之后线性地址按该地址空间翻译；deactivate 回到内核页目录。 */
void aspace_activate(const aspace_t *as);
void aspace_deactivate(void);
/* 销毁：释放所有数据页、页表、页目录。不能销毁当前正在使用的（调用者先 deactivate）。 */
void aspace_destroy(aspace_t *as);

#endif

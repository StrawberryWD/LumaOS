/* Draw a single character in graphics mode */
/* ---- DAY63: font resource. File format "LFNT" (tools/mkfont.py writes it; build.sh puts it on the ISO as
 * FONTS/SYS8X8.FNT):   +0 "LFNT"  +4 version(1)  +5 first char(32)  +6 glyph count(95)  +7 glyph height(8)
 *                       +8 count*height bytes, one byte per row, MSB = leftmost pixel.
 * font_load() validates the header and the exact length BEFORE touching the table, so a bad file leaves the
 * built-in font in place. */
static const char *font_src = "built-in";
int font_load(const unsigned char *d, unsigned len, const char *source)
{
    if (!d || len != 8u + 95u * 8u) return -1;
    if (d[0] != 'L' || d[1] != 'F' || d[2] != 'N' || d[3] != 'T') return -2;
    if (d[4] != 1 || d[5] != 32 || d[6] != 95 || d[7] != 8) return -3;
    for (int g = 0; g < 95; g++)
        for (int r = 0; r < 8; r++)
            font_bitmap[g][r] = d[8 + g * 8 + r];
    font_src = source ? source : "file";
    return 0;
}
const char *font_source(void) { return font_src; }
unsigned font_checksum(void)          /* FNV-1a over the 95x8 table: the same value tools/mkfont.py prints */
{
    unsigned h = 2166136261u;
    for (int g = 0; g < 95; g++)
        for (int r = 0; r < 8; r++) { h ^= font_bitmap[g][r]; h *= 16777619u; }
    return h;
}

void vga_draw_char(int x, int y, char c, unsigned char color)
{
    if (c < 32 || c > 126) return;

    const unsigned char *bitmap = font_bitmap[(unsigned char)c - 32];

    for (int row = 0; row < 8; row++) {
        unsigned char byte = bitmap[row];
        for (int col = 0; col < 8; col++) {
            if (byte & (0x80 >> col)) {
                vga_put_pixel(x + col, y + row, color);
            }
        }
    }
}

/* === MODIFIED SECTION START ===
 * STAGE4 FIX (text truncation / wrap-to-wrong-width bug):
 *
 * vga_draw_string() used to wrap only at the *screen* edge
 * (FONT_SCREEN_W = 800), regardless of which widget/window it was
 * drawing into. A label rendered inside a narrow window (titlebar,
 * dock label, settings row, terminal input line, etc.) would never
 * wrap against that window's own right edge — it just kept drawing
 * straight past it until it happened to reach column ~800, which
 * produces exactly the "text cut off / doesn't wrap" symptom users
 * see in anything narrower than the full screen.
 *
 * Fix: vga_draw_string() is now a thin wrapper around the new
 * vga_draw_string_clipped(), which takes an explicit maximum width
 * (in pixels) to wrap/clip against. Existing call sites that don't
 * care about a specific widget width keep working unchanged (they
 * still get the old full-screen-width behaviour via FONT_SCREEN_W),
 * while any caller that knows its own widget width can now pass it
 * explicitly and get correct per-widget wrapping instead of bleeding
 * into neighbouring UI.
 */
void vga_draw_string_clipped(int x, int y, char *str, unsigned char color, int max_w)
{
    int cx = x;
    int cy = y;
    int right_edge = x + max_w; /* pixels; if max_w<=0, effectively no clip */

    while (*str) {
        if (*str == '\n') {
            cx = x;
            cy += 10;
        } else if (*str == ' ') {
            cx += 8;
        } else {
            /* Only draw the glyph if it still fits inside the caller's
             * width — prevents bleed-through into whatever is drawn
             * to the right of this widget (adjacent buttons, window
             * border, next dock icon, etc). */
            if (max_w <= 0 || cx + 8 <= right_edge)
                vga_draw_char(cx, cy, *str, color);
            cx += 8;
        }
        str++;

        /* Wrap to next line once we run out of room in *this* widget
         * (max_w>0), falling back to the old full-screen wrap when no
         * width was supplied (max_w<=0), so unclipped callers keep
         * their previous behaviour exactly. */
        if (max_w > 0) {
            if (cx + 8 >= right_edge) {
                cx = x;
                cy += 10;
            }
        } else if (cx + 8 >= FONT_SCREEN_W) {
            cx = x;
            cy += 10;
        }
    }
}

/* Backward-compatible entry point: no explicit width means "wrap at
 * the screen edge", same as before. Prefer vga_draw_string_clipped()
 * for anything drawn inside a window/widget narrower than the screen. */
void vga_draw_string(int x, int y, char *str, unsigned char color)
{
    vga_draw_string_clipped(x, y, str, color, 0);
}
/* === MODIFIED SECTION END === */

